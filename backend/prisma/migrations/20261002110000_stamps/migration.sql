-- Stamps (a stamp is a row in "photo"): the photo becomes optional, a stamp can carry a song, and at least one of
-- photo, caption or song must exist. "Shared to the venue page" and the night rollover are gone.
-- Hand-written guarantees below replace the triggers that referred to shared and night.

-- 1. Retire the night machinery before its columns go.
DROP TRIGGER IF EXISTS photo_set_night ON "photo";
DROP FUNCTION IF EXISTS lastcall_photo_set_night();
DROP FUNCTION IF EXISTS lastcall_night_of(timestamptz);
DROP FUNCTION IF EXISTS lastcall_night_end(text);

-- 2. Schema changes (generated by prisma migrate diff).
-- DropIndex
DROP INDEX "photo_user_id_venue_id_night_idx";

-- DropIndex
DROP INDEX "photo_venue_id_night_idx";

-- AlterTable
ALTER TABLE "photo" DROP COLUMN "night",
DROP COLUMN "shared",
ADD COLUMN     "song_art_url" TEXT,
ADD COLUMN     "song_artist" TEXT,
ADD COLUMN     "song_source_id" TEXT,
ADD COLUMN     "song_title" TEXT,
ALTER COLUMN "storage_key" DROP NOT NULL,
ALTER COLUMN "mime_type" DROP NOT NULL;

-- CreateIndex
CREATE INDEX "photo_created_at_id_idx" ON "photo"("created_at", "id");

-- 3. A stamp has a photo, a caption, a song, or any mix, and nothing else is a stamp.
ALTER TABLE "photo" ADD CONSTRAINT photo_has_content
  CHECK (storage_key IS NOT NULL OR btrim(caption) <> '' OR song_title IS NOT NULL);
-- A photo has both its key and its type, or neither.
ALTER TABLE "photo" ADD CONSTRAINT photo_storage_pair CHECK ((storage_key IS NULL) = (mime_type IS NULL));
-- A song has a title and an artist; the other song fields only exist with a song. Bounded lengths, https art only.
ALTER TABLE "photo" ADD CONSTRAINT photo_song_shape CHECK (
  (song_title IS NULL AND song_artist IS NULL AND song_art_url IS NULL AND song_source_id IS NULL)
  OR (song_title IS NOT NULL AND song_artist IS NOT NULL
      AND char_length(btrim(song_title)) BETWEEN 1 AND 200 AND char_length(btrim(song_artist)) BETWEEN 1 AND 200
      AND (song_art_url IS NULL OR (song_art_url LIKE 'https://%' AND char_length(song_art_url) <= 500))
      AND (song_source_id IS NULL OR char_length(song_source_id) <= 100))
);

-- 4. Stamps stay immutable except caption, song, edited_at, moderation state (hidden_at) and removed_at (final).
-- Everything that says who, where, when and what was photographed is fixed, including the rating.
CREATE OR REPLACE FUNCTION lastcall_photo_immutable() RETURNS trigger AS $$
BEGIN
  IF (NEW.id, NEW.user_id, NEW.venue_id, NEW.storage_key, NEW.mime_type, NEW.lat, NEW.lng, NEW.created_at, NEW.rating, NEW.countable)
     IS DISTINCT FROM (OLD.id, OLD.user_id, OLD.venue_id, OLD.storage_key, OLD.mime_type, OLD.lat, OLD.lng, OLD.created_at, OLD.rating, OLD.countable) THEN
    RAISE EXCEPTION 'lastcall: stamps are immutable except caption, song, moderation state and removal' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF OLD.removed_at IS NOT NULL AND NEW.removed_at IS DISTINCT FROM OLD.removed_at THEN
    RAISE EXCEPTION 'lastcall: a removed stamp stays removed' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 5. Likes: only on someone else's visible stamp by a live account, and never on App Review stamps.
-- FOR SHARE so a concurrent removal or hide can't interleave with the insert.
CREATE OR REPLACE FUNCTION lastcall_like_guard() RETURNS trigger AS $$
DECLARE p record;
BEGIN
  SELECT ph.user_id, ph.hidden_at, ph.removed_at, ph.countable, u.deleted_at
    INTO p
    FROM "photo" ph JOIN "app_user" u ON u.id = ph.user_id
    WHERE ph.id = NEW.photo_id
    FOR SHARE OF ph;
  IF p.user_id = NEW.user_id THEN
    RAISE EXCEPTION 'lastcall: you can''t like your own stamp' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF p.hidden_at IS NOT NULL OR p.removed_at IS NOT NULL OR NOT p.countable OR p.deleted_at IS NOT NULL THEN
    RAISE EXCEPTION 'lastcall: this stamp can''t be liked' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 6. Rate-limit kinds: song search joins follow, like and post.
ALTER TABLE "rate_event" DROP CONSTRAINT rate_event_kind;
ALTER TABLE "rate_event" ADD CONSTRAINT rate_event_kind CHECK (kind IN ('follow', 'like', 'post', 'song_search'));
