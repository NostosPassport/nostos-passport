// Regenerates shared/stamp-font-metrics.ts from the Source Serif 4 SemiBold file the app and web build ship.
// Usage: node scripts/generate-stamp-font-metrics.mjs <path to SourceSerif4_600SemiBold.ttf> <path to opentype.js entry>
// opentype.js is a one-off dev tool and is intentionally not a repository dependency (npm i opentype.js@1.3.4 elsewhere).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const [, , ttf, otPath] = process.argv;
const require = createRequire(import.meta.url);
const opentype = require(otPath);
const font = opentype.loadSync(ttf);
const upm = font.unitsPerEm;
const ranges = [[0x20, 0x7e], [0xa0, 0x24f], [0x370, 0x3ff], [0x400, 0x4ff], [0x1e00, 0x1eff], [0x2010, 0x2027], [0x2030, 0x203a], [0x20ac, 0x20ac]];
const entries = [];
for (const [a, b] of ranges) {
  for (let cp = a; cp <= b; cp++) {
    const g = font.charToGlyph(String.fromCodePoint(cp));
    if (!g || g.index === 0) continue;
    entries.push([cp, Math.round((g.advanceWidth / upm) * 1000)]);
  }
}
const os2 = font.tables.os2;
const out = `/** GENERATED by scripts/generate-stamp-font-metrics.mjs from Source Serif 4 SemiBold. Do not edit by hand. */
export const STAMP_FONT_FAMILY = "Source Serif 4";
/** Advance widths in 1/1000 em, no kerning. Characters missing here (CJK, Arabic, ...) use the system fallback font. */
export const STAMP_FONT_ADVANCE: Readonly<Record<number, number>> = {
${entries.map(([cp, w]) => `  ${cp}: ${w},`).join("\n")}
};
export const STAMP_FONT_CAP_HEIGHT = ${Math.round(((os2.sCapHeight ?? 0.66 * upm) / upm) * 1000)};
export const STAMP_FONT_X_HEIGHT = ${Math.round(((os2.sxHeight ?? 0.47 * upm) / upm) * 1000)};
`;
writeFileSync(new URL("../shared/stamp-font-metrics.ts", import.meta.url), out);
console.log(`wrote ${entries.length} glyphs, upm ${upm}`);
